# frozen_string_literal: true

# Site content as Ruby seed files, so any database (e.g. production) can be made
# identical to the one they were generated from (e.g. local).
#
#   bin/rails content_seed:dump   # writes db/seeds/content/*.rb and db/seeds/files/ (commit both)
#   bin/rails db:seed             # loads them (see db/seeds.rb)
#
# Loading REPLACES every content table below and the images/files attached to those
# records. Leads (and their uploaded files), users and Solid Queue are left untouched.
module ContentSeed
  CONTENT_DIR = Rails.root.join("db/seeds/content")
  FILES_DIR   = Rails.root.join("db/seeds/files")

  # Load order (parents first); deletes run in reverse.
  TABLES = %w[
    categories subcategories solutions products projects projects_solutions
    posts safety_articles clients departments documents content_lists settings translations
  ].freeze

  # Models whose attachments are site content (Lead is deliberately absent).
  RECORD_TYPES = %w[Category Client Document Post Product Project Solution].freeze

  HEADER = "# frozen_string_literal: true\n\n# Generated by `bin/rails content_seed:dump`. Regenerate it instead of editing by hand.\n"

  module_function

  def conn = ActiveRecord::Base.connection
  def available? = CONTENT_DIR.join("#{format('%02d', TABLES.size + 1)}_attachments.rb").exist?

  # ---- seed-file DSL (called from db/seeds/content/*.rb) ----------------------
  def table(name, rows) = (@tables ||= {})[name] = rows
  def attachments(rows) = @attachments = rows

  # ---- dump -------------------------------------------------------------------
  def dump!
    FileUtils.rm_rf([ CONTENT_DIR, FILES_DIR ])
    FileUtils.mkdir_p([ CONTENT_DIR, FILES_DIR ])

    keys_by_blob_id = {}
    attachments = ActiveStorage::Attachment.where(record_type: RECORD_TYPES).includes(:blob).order(:id).filter_map do |a|
      b = a.blob
      unless b.service.exist?(b.key)
        warn "skipped: #{a.record_type} ##{a.record_id} #{a.name} (#{b.filename}): file missing in storage"
        next
      end
      path = FILES_DIR.join(b.key)
      File.binwrite(path, b.download) unless path.exist?
      keys_by_blob_id[b.id.to_s] = b.key
      { record_type: a.record_type, record_id: a.record_id, name: a.name, created_at: a.created_at.utc.iso8601(6),
        blob: { key: b.key, filename: b.filename.to_s, content_type: b.content_type, metadata: b.metadata,
                byte_size: b.byte_size, checksum: b.checksum, created_at: b.created_at.utc.iso8601(6) } }
    end

    TABLES.each_with_index do |t, i|
      json_cols = conn.columns(t).select { |c| c.sql_type.start_with?("json") }.map(&:name)
      order = conn.column_exists?(t, :id) ? "id" : "1"
      rows = conn.select_all("SELECT * FROM #{conn.quote_table_name(t)} ORDER BY #{order}").to_a.map do |r|
        json_cols.each { |c| r[c] = JSON.parse(r[c]) if r[c].is_a?(String) }
        r.transform_values! { |v| v.is_a?(Time) ? v.utc.iso8601(6) : (v.is_a?(Date) ? v.iso8601 : v) }
        # image labels are keyed by blob id, which changes on load: key them by blob key instead
        if t == "products" && r["image_labels"].is_a?(Hash)
          r["image_labels"] = r["image_labels"].filter_map { |id, v| [ keys_by_blob_id[id], v ] if keys_by_blob_id[id] }.to_h
        end
        r
      end
      write("#{format('%02d', i + 1)}_#{t}.rb", "ContentSeed.table #{t.inspect}, #{literal(rows)}\n")
      puts "#{t.ljust(20)} #{rows.size}"
    end

    write("#{format('%02d', TABLES.size + 1)}_attachments.rb", "ContentSeed.attachments #{literal(attachments)}\n")
    puts "attachments          #{attachments.size} (#{keys_by_blob_id.values.uniq.size} files)"
  end

  def write(name, body) = File.write(CONTENT_DIR.join(name), "#{HEADER}\n#{body}")

  # One column per line for rows; nested JSON values stay on one line.
  def literal(rows)
    return "[]" if rows.empty?
    body = rows.map do |r|
      fields = r.map { |k, v| "    #{k}: #{v.inspect}," }
      "  {\n#{fields.join("\n")}\n  },"
    end
    "[\n#{body.join("\n")}\n]"
  end

  # ---- load -------------------------------------------------------------------
  def load!
    @tables = {}; @attachments = nil
    Dir[CONTENT_DIR.join("*.rb")].sort.each { |f| Kernel.load(f) }
    missing_tables = TABLES - @tables.keys
    raise "Seed files missing for: #{missing_tables.join(', ')}" if missing_tables.any?
    attachments = (@attachments || []).map(&:deep_stringify_keys)
    missing = attachments.map { |a| a["blob"]["key"] }.uniq.reject { |k| FILES_DIR.join(k).exist? }
    raise "Seed files missing in db/seeds/files: #{missing.first(5).join(', ')}" if missing.any?

    old_version = Setting.content_version
    old_files   = nil

    ActiveRecord::Base.transaction do
      old_files = remove_content_attachments
      TABLES.reverse_each { |t| conn.execute("DELETE FROM #{conn.quote_table_name(t)}") }
      TABLES.each do |t|
        insert_rows(t, @tables[t].map(&:stringify_keys))
        conn.reset_pk_sequence!(t) if conn.column_exists?(t, :id)
        puts "   #{t.ljust(20)} #{@tables[t].size}"
      end

      new_ids = {} # blob key in the seed files -> new blob id
      attachments.each do |a|
        b = a["blob"]
        new_ids[b["key"]] ||= begin
          blob = ActiveStorage::Blob.new(b.except("key").merge("key" => ActiveStorage::Blob.generate_unique_secure_token,
                                                                 "service_name" => ActiveStorage::Blob.service.name))
          File.open(FILES_DIR.join(b["key"]), "rb") { |io| blob.upload_without_unfurling(io) }
          blob.save!
          blob.id
        end
      end
      if attachments.any?
        ActiveStorage::Attachment.insert_all!(attachments.map { |a|
          a.slice("record_type", "record_id", "name", "created_at").merge("blob_id" => new_ids[a["blob"]["key"]])
        })
      end
      Product.where.not(image_labels: {}).find_each do |p|
        p.update_column(:image_labels, p.image_labels.filter_map { |key, v| [ new_ids[key].to_s, v ] if new_ids[key] }.to_h)
      end
      puts "   attachments          #{attachments.size} (#{new_ids.size} files)"

      # past any version the site has cached, so every page rebuilds from the new rows
      conn.execute("UPDATE settings SET content_version = #{[ old_version, Setting.content_version ].max + 1}")
    end

    delete_files(old_files)
  end

  def insert_rows(table, rows)
    return if rows.empty?
    existing = conn.columns(table).map(&:name)
    extra = rows.first.keys - existing
    warn "   #{table}: ignoring columns not in this database: #{extra.join(', ')}" if extra.any?
    cols = rows.first.keys & existing
    rows.each_slice(200) do |slice|
      values = slice.map { |r| "(#{cols.map { |c| v = r[c]; conn.quote(v.is_a?(Hash) || v.is_a?(Array) ? v.to_json : v) }.join(', ')})" }
      conn.execute("INSERT INTO #{conn.quote_table_name(table)} (#{cols.map { |c| conn.quote_column_name(c) }.join(', ')}) VALUES #{values.join(",\n")}")
    end
  end

  # Deletes the content attachments, their blobs and the blobs' variants (rows only);
  # returns [key, service_name] pairs whose files are removed after the commit.
  def remove_content_attachments
    blob_ids = ActiveStorage::Attachment.where(record_type: RECORD_TYPES).distinct.pluck(:blob_id)
    ActiveStorage::Attachment.where(record_type: RECORD_TYPES).delete_all
    blob_ids -= ActiveStorage::Attachment.where(blob_id: blob_ids).pluck(:blob_id) # still used elsewhere (e.g. a lead)

    variant_ids  = ActiveStorage::VariantRecord.where(blob_id: blob_ids).pluck(:id)
    variant_atts = ActiveStorage::Attachment.where(record_type: "ActiveStorage::VariantRecord", record_id: variant_ids)
    variant_blob_ids = variant_atts.pluck(:blob_id)
    variant_atts.delete_all
    ActiveStorage::VariantRecord.where(id: variant_ids).delete_all

    all_ids = blob_ids + variant_blob_ids
    files = ActiveStorage::Blob.where(id: all_ids).pluck(:key, :service_name)
    ActiveStorage::Blob.where(id: all_ids).delete_all
    files
  end

  def delete_files(files)
    Array(files).each do |key, service_name|
      service = (ActiveStorage::Blob.services.fetch(service_name) rescue ActiveStorage::Blob.service)
      service.delete(key)
      service.delete_prefixed("variants/#{key}/")
    rescue StandardError => e
      warn "   could not delete file #{key}: #{e.message}"
    end
  end
end
